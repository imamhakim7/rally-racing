// Generates src/stage/data/index.ts — a static import of every stage JSON.
//
// Why a generated index instead of Vite's `import.meta.glob`: the index must
// resolve in *every* runtime the stage library is used from, and `import.meta.glob`
// is a Vite-only transform (undefined under plain `bun`/`node` test runners).
// A committed index keeps the browser bundle, Vite dev server and headless test
// runners identical. Adding a stage still needs no code change: drop in the JSON
// and run `bun run gen:stages` (also wired to run before `dev` and `build`).
import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = resolve(process.cwd(), "src/stage/data");
const files = readdirSync(dir)
  .filter((file) => file.endsWith(".json"))
  .sort();

const identifier = (file: string): string =>
  file
    .replace(/\.json$/, "")
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, c: string) => c.toUpperCase());

const lines: string[] = [
  "// AUTO-GENERATED by scripts/generate-stage-index.ts — do not edit by hand.",
  "// Regenerate with `bun run gen:stages` (runs automatically before dev/build).",
  "",
];
for (const file of files) lines.push(`import ${identifier(file)} from "./${file}";`);
lines.push("");
lines.push("export const stageModules: Record<string, { default: unknown }> = {");
for (const file of files) lines.push(`  ${JSON.stringify(file)}: { default: ${identifier(file)} },`);
lines.push("};");
lines.push("");

writeFileSync(join(dir, "index.ts"), lines.join("\n"));
console.log(`stage index: ${files.length} stage(s) -> src/stage/data/index.ts`);
